"""Embed pinned read-only validators in signed package JavaScript; no image change."""
from pathlib import Path
import hashlib
import json

HERE = Path(__file__).resolve().parent
names = ('market_terms', 'pilot_contract', 'reverse_contract')
sources = {name: (HERE/(name+'.py')).read_text() for name in names}
main = (HERE/'validate_upgrade.py').read_text()
program = 'import sys,types\nsys.dont_write_bytecode=True\n'
program += 'sources=' + repr(sources) + '\n'
program += "for name,source in sources.items():\n m=types.ModuleType(name);sys.modules[name]=m;exec(compile(source,name+'.py','exec'),m.__dict__)\n"
program += main
target = HERE.parents[2]/'startos/live/legacyUpgradeProgram.ts'
target.write_text('// Generated by scripts/suitbox/legacy/embed.py; do not edit.\n'
                  '// Pure contract validators retained from legacy checkpoint 77810adc.\n'
                  'export const legacyUpgradeProgram = ' + json.dumps(program) + '\n')
print('Embedded read-only legacy validator:', hashlib.sha256(program.encode()).hexdigest())
